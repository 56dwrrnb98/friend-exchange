create or replace function public.edit_market(
  p_market_id bigint,
  p_question text,
  p_description text,
  p_close_mode text,
  p_closes_at timestamptz,
  p_outcomes jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_is_admin boolean := false;
  v_market public.markets%rowtype;
  v_question text := btrim(coalesce(p_question, ''));
  v_description text := nullif(btrim(coalesce(p_description, '')), '');
  v_close_mode text := lower(btrim(coalesce(p_close_mode, '')));
  v_outcome_count integer;
  v_existing_outcome_count integer;
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  select coalesce(is_admin, false)
  into v_is_admin
  from public.profiles
  where id = v_user_id;

  if not v_is_admin then
    raise exception 'Only an administrator can edit a market.';
  end if;

  if char_length(v_question) < 5 or char_length(v_question) > 180 then
    raise exception 'Questions must be between 5 and 180 characters.';
  end if;

  if v_description is not null and char_length(v_description) > 600 then
    raise exception 'Details cannot exceed 600 characters.';
  end if;

  if v_close_mode not in ('date', 'outcome') then
    raise exception 'Choose when predictions should close.';
  end if;

  if v_close_mode = 'date' and (p_closes_at is null or p_closes_at <= now()) then
    raise exception 'The corrected closing time must be in the future.';
  end if;

  if v_close_mode = 'outcome' and p_closes_at is not null then
    raise exception 'Open-until-outcome markets cannot have a scheduled closing time.';
  end if;

  select *
  into v_market
  from public.markets
  where id = p_market_id
  for update;

  if not found then
    raise exception 'Market not found.';
  end if;

  if v_market.status <> 'open' then
    raise exception 'Only open markets can be edited.';
  end if;

  if p_outcomes is null or jsonb_typeof(p_outcomes) <> 'array' then
    raise exception 'Include every existing outcome.';
  end if;

  v_outcome_count := jsonb_array_length(p_outcomes);

  select count(*)
  into v_existing_outcome_count
  from public.outcomes
  where market_id = p_market_id;

  if v_outcome_count <> v_existing_outcome_count then
    raise exception 'Outcomes cannot be added or removed.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_outcomes) as item(value)
    where jsonb_typeof(item.value) <> 'object'
       or coalesce(item.value ->> 'id', '') !~ '^[0-9]+$'
  ) then
    raise exception 'Every outcome correction must include a valid outcome ID.';
  end if;

  if (
    select count(*) <> count(distinct (item.value ->> 'id')::bigint)
    from jsonb_array_elements(p_outcomes) as item(value)
  ) then
    raise exception 'Each existing outcome must be included exactly once.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_outcomes) as item(value)
    where char_length(btrim(coalesce(item.value ->> 'label', ''))) < 1
       or char_length(btrim(coalesce(item.value ->> 'label', ''))) > 80
  ) then
    raise exception 'Each outcome must be between 1 and 80 characters.';
  end if;

  if (
    select count(*) <> count(distinct lower(btrim(item.value ->> 'label')))
    from jsonb_array_elements(p_outcomes) as item(value)
  ) then
    raise exception 'Outcome names must be unique.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_outcomes) as item(value)
    left join public.outcomes as outcome
      on outcome.id = (item.value ->> 'id')::bigint
     and outcome.market_id = p_market_id
    where outcome.id is null
  ) then
    raise exception 'Outcome corrections must belong to this market.';
  end if;

  perform 1
  from public.outcomes
  where market_id = p_market_id
  for update;

  update public.markets
  set
    question = v_question,
    description = v_description,
    close_mode = v_close_mode,
    closes_at = p_closes_at
  where id = p_market_id;

  update public.outcomes as outcome
  set label = btrim(edit.label)
  from jsonb_to_recordset(p_outcomes) as edit(id bigint, label text)
  where outcome.id = edit.id
    and outcome.market_id = p_market_id;

  return p_market_id;
end;
$$;

create or replace function public.place_prediction(
  p_market_id bigint,
  p_outcome_id bigint,
  p_amount bigint
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_profile public.profiles%rowtype;
  v_market public.markets%rowtype;
  v_outcome_market_id bigint;
  v_prediction_id bigint;
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  if p_amount is null or p_amount < 1 then
    raise exception 'Prediction amount must be at least 1 point.';
  end if;

  select *
  into v_profile
  from public.profiles
  where id = v_user_id
  for update;

  if not found then
    raise exception 'Profile not found.';
  end if;

  if v_profile.balance < p_amount then
    raise exception 'You do not have enough available points.';
  end if;

  select *
  into v_market
  from public.markets
  where id = p_market_id
  for update;

  if not found then
    raise exception 'Market not found.';
  end if;

  if v_market.status <> 'open' then
    raise exception 'This market is no longer open.';
  end if;

  if v_market.close_mode = 'date' and now() >= v_market.closes_at then
    raise exception 'Predictions are closed for this market.';
  end if;

  select market_id
  into v_outcome_market_id
  from public.outcomes
  where id = p_outcome_id;

  if not found or v_outcome_market_id <> p_market_id then
    raise exception 'That outcome does not belong to this market.';
  end if;

  update public.profiles
  set balance = balance - p_amount
  where id = v_user_id;

  insert into public.predictions (
    user_id,
    market_id,
    outcome_id,
    amount
  )
  values (
    v_user_id,
    p_market_id,
    p_outcome_id,
    p_amount
  )
  returning id into v_prediction_id;

  insert into public.point_transactions (
    user_id,
    market_id,
    amount,
    kind,
    note
  )
  values (
    v_user_id,
    p_market_id,
    -p_amount,
    'prediction',
    'Prediction placed'
  );

  return v_prediction_id;
end;
$$;

create or replace function public.resolve_market(
  p_market_id bigint,
  p_winning_outcome_id bigint,
  p_resolution_note text,
  p_outcome_known_at timestamptz,
  p_resolution_source_url text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_market public.markets%rowtype;
  v_is_admin boolean := false;
  v_outcome_market_id bigint;
  v_source_url text := nullif(btrim(coalesce(p_resolution_source_url, '')), '');
  v_eligibility_cutoff_at timestamptz;
  v_total_pool bigint := 0;
  v_winning_pool bigint := 0;
  v_payout_total bigint := 0;
  v_late_refund_total bigint := 0;
  v_late_prediction_count bigint := 0;
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  if nullif(btrim(p_resolution_note), '') is null then
    raise exception 'A resolution note is required.';
  end if;

  if char_length(btrim(p_resolution_note)) > 280 then
    raise exception 'The resolution note must be 280 characters or fewer.';
  end if;

  if p_outcome_known_at is null then
    raise exception 'Enter when the outcome became known.';
  end if;

  if p_outcome_known_at > now() then
    raise exception 'The outcome-known time cannot be in the future.';
  end if;

  if v_source_url is not null and (
    char_length(v_source_url) > 2048
    or v_source_url !~* '^https?://'
  ) then
    raise exception 'The source link must be a valid http or https URL.';
  end if;

  select coalesce(is_admin, false)
  into v_is_admin
  from public.profiles
  where id = v_user_id;

  select *
  into v_market
  from public.markets
  where id = p_market_id
  for update;

  if not found then
    raise exception 'Market not found.';
  end if;

  if v_market.creator_id <> v_user_id and not v_is_admin then
    raise exception 'Only the market creator or an administrator can resolve this market.';
  end if;

  if v_market.status <> 'open' then
    raise exception 'This market has already been resolved or voided.';
  end if;

  select market_id
  into v_outcome_market_id
  from public.outcomes
  where id = p_winning_outcome_id;

  if not found or v_outcome_market_id <> p_market_id then
    raise exception 'That outcome does not belong to this market.';
  end if;

  v_eligibility_cutoff_at := case
    when v_market.close_mode = 'date'
      then least(v_market.closes_at, p_outcome_known_at)
    else p_outcome_known_at
  end;

  select coalesce(sum(amount), 0)
  into v_total_pool
  from public.predictions
  where market_id = p_market_id
    and created_at < v_eligibility_cutoff_at;

  select coalesce(sum(amount), 0)
  into v_winning_pool
  from public.predictions
  where market_id = p_market_id
    and outcome_id = p_winning_outcome_id
    and created_at < v_eligibility_cutoff_at;

  insert into public.market_payouts (market_id, user_id, amount, kind)
  select
    p_market_id,
    user_id,
    sum(amount)::bigint,
    'late_refund'
  from public.predictions
  where market_id = p_market_id
    and created_at >= v_eligibility_cutoff_at
  group by user_id;

  select
    coalesce(sum(amount), 0),
    count(*)
  into v_late_refund_total, v_late_prediction_count
  from public.predictions
  where market_id = p_market_id
    and created_at >= v_eligibility_cutoff_at;

  -- If nobody backed the real winner, refund every participant.
  if v_total_pool > 0 and v_winning_pool = 0 then
    insert into public.market_payouts (market_id, user_id, amount, kind)
    select
      p_market_id,
      user_id,
      sum(amount)::bigint,
      'no_winner_refund'
    from public.predictions
    where market_id = p_market_id
      and created_at < v_eligibility_cutoff_at
    group by user_id;
  elsif v_winning_pool > 0 then
    -- Distribute the eligible pool among winning users in proportion to
    -- their eligible stake. Integer-rounding leftovers use the established
    -- deterministic largest-remainder rule.
    with stakes as (
      select
        user_id,
        sum(amount)::bigint as stake
      from public.predictions
      where market_id = p_market_id
        and outcome_id = p_winning_outcome_id
        and created_at < v_eligibility_cutoff_at
      group by user_id
    ),
    raw_payouts as (
      select
        user_id,
        stake,
        (stake::numeric * v_total_pool::numeric / v_winning_pool::numeric) as exact_payout
      from stakes
    ),
    rounded as (
      select
        user_id,
        floor(exact_payout)::bigint as base_payout,
        exact_payout - floor(exact_payout) as fractional_remainder
      from raw_payouts
    ),
    ranked as (
      select
        user_id,
        base_payout,
        row_number() over (order by fractional_remainder desc, user_id) as remainder_rank,
        (v_total_pool - sum(base_payout) over ())::bigint as leftover_points
      from rounded
    )
    insert into public.market_payouts (market_id, user_id, amount, kind)
    select
      p_market_id,
      user_id,
      base_payout + case when remainder_rank <= leftover_points then 1 else 0 end,
      'winner'
    from ranked;
  end if;

  update public.profiles as profile
  set balance = profile.balance + credit.amount
  from (
    select user_id, sum(amount)::bigint as amount
    from public.market_payouts
    where market_id = p_market_id
    group by user_id
  ) as credit
  where credit.user_id = profile.id;

  insert into public.point_transactions (
    user_id,
    market_id,
    amount,
    kind,
    note
  )
  select
    user_id,
    market_id,
    amount,
    case when kind = 'winner' then 'payout' else 'refund' end,
    case kind
      when 'winner' then 'Winning market payout'
      when 'late_refund' then 'Prediction refunded because it was submitted after the eligibility cutoff'
      else 'Refunded because nobody selected the winning outcome'
    end
  from public.market_payouts
  where market_id = p_market_id;

  select coalesce(sum(amount), 0)
  into v_payout_total
  from public.market_payouts
  where market_id = p_market_id
    and kind in ('winner', 'no_winner_refund');

  if v_payout_total <> v_total_pool then
    raise exception 'Payout calculation failed to distribute the full eligible pool.';
  end if;

  update public.markets
  set
    status = 'resolved',
    winning_outcome_id = p_winning_outcome_id,
    resolution_note = btrim(p_resolution_note),
    outcome_known_at = p_outcome_known_at,
    eligibility_cutoff_at = v_eligibility_cutoff_at,
    resolution_source_url = v_source_url,
    resolved_by = v_user_id,
    resolved_at = now()
  where id = p_market_id;

  return jsonb_build_object(
    'market_id', p_market_id,
    'total_pool', v_total_pool,
    'winning_pool', v_winning_pool,
    'payout_total', v_payout_total,
    'late_refund_total', v_late_refund_total,
    'late_prediction_count', v_late_prediction_count,
    'eligibility_cutoff_at', v_eligibility_cutoff_at,
    'refunded', v_total_pool > 0 and v_winning_pool = 0
  );
end;
$$;

