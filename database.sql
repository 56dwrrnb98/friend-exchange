create or replace function public.process_closing_soon_notifications(
  p_now timestamptz default now()
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_market record;
  v_notification_id bigint;
  v_created_count integer := 0;
begin
  for v_market in
    select
      market.id,
      market.creator_id,
      case
        when market.closes_at - market.created_at >= interval '24 hours'
          then '24 hours'
        else '1 hour'
      end as reminder_label
    from public.markets as market
    where market.status = 'open'
      and market.close_mode = 'date'
      and market.closes_at > p_now
      and market.closes_at - market.created_at >= interval '1 hour'
      and (
        (
          market.closes_at - market.created_at >= interval '24 hours'
          and p_now >= market.closes_at - interval '24 hours'
        )
        or (
          market.closes_at - market.created_at < interval '24 hours'
          and p_now >= market.closes_at - interval '1 hour'
        )
      )
      and not exists (
        select 1
        from public.notifications as notification
        where notification.market_id = market.id
          and notification.kind = 'closing_soon'
          and notification.is_test = false
      )
    order by market.closes_at
  loop
    v_notification_id := public.enqueue_market_notification(
      'closing_soon',
      v_market.id,
      v_market.creator_id,
      v_market.reminder_label
    );

    if v_notification_id is not null then
      v_created_count := v_created_count + 1;
    end if;
  end loop;

  return jsonb_build_object(
    'processed_at', p_now,
    'notifications_created', v_created_count
  );
end;
$$;

