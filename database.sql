create or replace function public.enqueue_market_notification(
  p_kind text,
  p_market_id bigint,
  p_actor_id uuid,
  p_reminder_label text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_mode text := 'off';
  v_market public.markets%rowtype;
  v_actor_name text;
  v_winner_label text;
  v_title text;
  v_body text;
  v_notification_id bigint;
  v_intended_count integer := 0;
begin
  select delivery_mode
  into v_mode
  from public.notification_system_settings
  where singleton = true;

  if coalesce(v_mode, 'off') = 'off' then
    return null;
  end if;

  if p_kind not in ('new_market', 'closing_soon', 'resolution', 'void') then
    raise exception 'Unsupported notification type.';
  end if;

  select *
  into v_market
  from public.markets
  where id = p_market_id;

  if not found then
    raise exception 'Market not found while preparing notification.';
  end if;

  select display_name
  into v_actor_name
  from public.profiles
  where id = coalesce(p_actor_id, v_market.creator_id);

  if p_kind = 'new_market' then
    v_title := 'New market listed';
    v_body := v_market.question || ' — opened by ' || coalesce(v_actor_name, 'a trader') || '.';
  elsif p_kind = 'closing_soon' then
    v_title := 'Predictions close soon';
    v_body := v_market.question || ' — closes in ' || coalesce(p_reminder_label, '24 hours') || '.';
  elsif p_kind = 'resolution' then
    select label
    into v_winner_label
    from public.outcomes
    where id = v_market.winning_outcome_id
      and market_id = v_market.id;

    v_title := 'Market resolved';
    v_body := v_market.question || ' — winner: ' || coalesce(v_winner_label, 'Outcome recorded') || '.';
  else
    v_title := 'Market voided';
    v_body := v_market.question || ' — committed points have been returned.';
  end if;

  select count(*)::integer
  into v_intended_count
  from public.profiles as profile
  where (
    v_mode = 'test'
    and profile.is_admin = true
  ) or (
    v_mode = 'live'
    and (p_kind <> 'new_market' or profile.id <> v_market.creator_id)
  );

  insert into public.notifications (
    kind,
    market_id,
    actor_id,
    title,
    body,
    target_url,
    delivery_mode,
    is_test,
    intended_recipient_count
  )
  values (
    p_kind,
    p_market_id,
    p_actor_id,
    v_title,
    v_body,
    '#/market/' || p_market_id,
    v_mode,
    false,
    v_intended_count
  )
  on conflict (kind, market_id)
    where is_test = false and market_id is not null
  do nothing
  returning id into v_notification_id;

  if v_notification_id is null then
    select id
    into v_notification_id
    from public.notifications
    where kind = p_kind
      and market_id = p_market_id
      and is_test = false;

    return v_notification_id;
  end if;

  insert into public.notification_recipients (notification_id, user_id)
  select
    v_notification_id,
    profile.id
  from public.profiles as profile
  where (
    v_mode = 'test'
    and profile.is_admin = true
  ) or (
    v_mode = 'live'
    and (p_kind <> 'new_market' or profile.id <> v_market.creator_id)
  )
  on conflict do nothing;

  insert into public.notification_deliveries (
    notification_id,
    user_id,
    subscription_id
  )
  select
    v_notification_id,
    recipient.user_id,
    subscription.id
  from public.notification_recipients as recipient
  join public.notification_preferences as preference
    on preference.user_id = recipient.user_id
  join public.push_subscriptions as subscription
    on subscription.user_id = recipient.user_id
   and subscription.disabled_at is null
  where recipient.notification_id = v_notification_id
    and case p_kind
      when 'new_market' then preference.new_market_push
      when 'closing_soon' then preference.closing_soon_push
      else preference.resolution_push
    end
  on conflict do nothing;

  return v_notification_id;
end;
$$;

create or replace function public.handle_market_notification_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    perform public.enqueue_market_notification(
      'new_market',
      new.id,
      new.creator_id,
      null
    );
  elsif old.status = 'open' and new.status = 'resolved' then
    perform public.enqueue_market_notification(
      'resolution',
      new.id,
      new.resolved_by,
      null
    );
  elsif old.status = 'open' and new.status = 'void' then
    perform public.enqueue_market_notification(
      'void',
      new.id,
      auth.uid(),
      null
    );
  end if;

  return new;
end;
$$;

