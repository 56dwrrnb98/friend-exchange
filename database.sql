create or replace function public.create_market(
  p_question text,
  p_description text,
  p_close_mode text,
  p_closes_at timestamptz,
  p_outcome_labels text[]
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_market_id bigint;
  v_question text := btrim(coalesce(p_question, ''));
  v_description text := nullif(btrim(coalesce(p_description, '')), '');
  v_close_mode text := lower(btrim(coalesce(p_close_mode, '')));
  v_outcome_count integer;
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  if char_length(v_question) < 5 or char_length(v_question) > 180 then
    raise exception 'Questions must be between 5 and 180 characters.';
  end if;

  if v_description is not null and char_length(v_description) > 600 then
    raise exception 'Details cannot exceed 600 characters.';
  end if;

  if v_close_mode not in ('date', 'outcome') then
    raise exception 'Choose when predictions should close.';
  end if;

  if v_close_mode = 'date' and (p_closes_at is null or p_closes_at <= now()) then
    raise exception 'The closing time must be in the future.';
  end if;

  if v_close_mode = 'outcome' and p_closes_at is not null then
    raise exception 'Open-until-outcome markets cannot have a scheduled closing time.';
  end if;

  v_outcome_count := coalesce(cardinality(p_outcome_labels), 0);
  if v_outcome_count < 2 or v_outcome_count > 6 then
    raise exception 'Markets must have between 2 and 6 outcomes.';
  end if;

  if exists (
    select 1
    from unnest(p_outcome_labels) as item(label)
    where char_length(btrim(coalesce(label, ''))) < 1
       or char_length(btrim(label)) > 80
  ) then
    raise exception 'Each outcome must be between 1 and 80 characters.';
  end if;

  if (
    select count(*) <> count(distinct lower(btrim(label)))
    from unnest(p_outcome_labels) as item(label)
  ) then
    raise exception 'Outcome names must be unique.';
  end if;

  insert into public.markets (
    creator_id,
    question,
    description,
    close_mode,
    closes_at
  )
  values (
    v_user_id,
    v_question,
    v_description,
    v_close_mode,
    p_closes_at
  )
  returning id into v_market_id;

  insert into public.outcomes (market_id, label, sort_order, seed_points)
  select
    v_market_id,
    btrim(item.label),
    item.ordinality::integer - 1,
    25
  from unnest(p_outcome_labels) with ordinality as item(label, ordinality);

  return v_market_id;
end;
$$;

