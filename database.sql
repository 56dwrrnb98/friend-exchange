create or replace function public.admin_send_notification_test(
  p_kind text,
  p_title text,
  p_body text,
  p_target_url text,
  p_subscription_ids uuid[] default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin_id uuid := auth.uid();
  v_kind text := lower(btrim(coalesce(p_kind, '')));
  v_title text := btrim(coalesce(p_title, ''));
  v_body text := btrim(coalesce(p_body, ''));
  v_target_url text := btrim(coalesce(p_target_url, ''));
  v_notification_id bigint;
  v_delivery_ids jsonb := '[]'::jsonb;
begin
  if v_admin_id is null then
    raise exception 'You must be signed in.';
  end if;

  if not exists (
    select 1
    from public.profiles
    where id = v_admin_id
      and is_admin = true
  ) then
    raise exception 'Only administrators can send notification tests.';
  end if;

  if v_kind not in ('new_market', 'closing_soon', 'resolution', 'void') then
    raise exception 'Choose a supported notification type.';
  end if;

  if char_length(v_title) not between 1 and 82 then
    raise exception 'Test titles must be between 1 and 82 characters.';
  end if;

  if char_length(v_body) not between 1 and 300 then
    raise exception 'Test messages must be between 1 and 300 characters.';
  end if;

  if v_target_url !~ '^#/(markets|market/[0-9]+)$' then
    raise exception 'Choose a valid Friend Exchange destination.';
  end if;

  insert into public.notifications (
    kind,
    actor_id,
    title,
    body,
    target_url,
    delivery_mode,
    is_test,
    intended_recipient_count
  )
  values (
    v_kind,
    v_admin_id,
    '[TEST] ' || v_title,
    v_body,
    v_target_url,
    'test',
    true,
    1
  )
  returning id into v_notification_id;

  insert into public.notification_recipients (notification_id, user_id)
  values (v_notification_id, v_admin_id);

  with inserted as (
    insert into public.notification_deliveries (
      notification_id,
      user_id,
      subscription_id
    )
    select
      v_notification_id,
      v_admin_id,
      subscription.id
    from public.push_subscriptions as subscription
    where subscription.user_id = v_admin_id
      and subscription.disabled_at is null
      and (
        p_subscription_ids is null
        or subscription.id = any(p_subscription_ids)
      )
    returning id
  )
  select coalesce(jsonb_agg(id order by id), '[]'::jsonb)
  into v_delivery_ids
  from inserted;

  return jsonb_build_object(
    'notification_id', v_notification_id,
    'delivery_ids', v_delivery_ids
  );
end;
$$;

create or replace function public.get_notification_admin_overview(
  p_limit integer default 30
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_admin_id uuid := auth.uid();
  v_limit integer := greatest(1, least(coalesce(p_limit, 30), 100));
  v_result jsonb;
begin
  if v_admin_id is null then
    raise exception 'You must be signed in.';
  end if;

  if not exists (
    select 1
    from public.profiles
    where id = v_admin_id
      and is_admin = true
  ) then
    raise exception 'Only administrators can view notification operations.';
  end if;

  select jsonb_build_object(
    'mode', setting.delivery_mode,
    'updated_at', setting.updated_at,
    'active_subscriptions', (
      select count(*)
      from public.push_subscriptions
      where disabled_at is null
    ),
    'pending_deliveries', (
      select count(*)
      from public.notification_deliveries
      where status in ('pending', 'processing')
    ),
    'failed_deliveries', (
      select count(*)
      from public.notification_deliveries
      where status in ('failed', 'expired')
    ),
    'last_successful_delivery_at', (
      select max(completed_at)
      from public.notification_deliveries
      where status = 'sent'
    ),
    'notifications', coalesce((
      select jsonb_agg(to_jsonb(recent_notification) order by recent_notification.created_at desc)
      from (
        select
          notification.id,
          notification.kind,
          notification.market_id,
          notification.title,
          notification.body,
          notification.delivery_mode,
          notification.is_test,
          notification.intended_recipient_count,
          notification.created_at,
          count(distinct recipient.user_id)::integer as actual_recipient_count,
          count(distinct delivery.id)::integer as delivery_count,
          count(distinct delivery.id) filter (where delivery.status = 'sent')::integer as sent_count,
          count(distinct delivery.id) filter (where delivery.status in ('failed', 'expired'))::integer as failed_count
        from public.notifications as notification
        left join public.notification_recipients as recipient
          on recipient.notification_id = notification.id
        left join public.notification_deliveries as delivery
          on delivery.notification_id = notification.id
        group by notification.id
        order by notification.created_at desc, notification.id desc
        limit v_limit
      ) as recent_notification
    ), '[]'::jsonb),
    'deliveries', coalesce((
      select jsonb_agg(to_jsonb(recent_delivery) order by recent_delivery.created_at desc)
      from (
        select
          delivery.id,
          delivery.notification_id,
          delivery.status,
          delivery.attempt_count,
          delivery.response_status,
          delivery.last_error,
          delivery.created_at,
          delivery.attempted_at,
          delivery.completed_at,
          subscription.device_label,
          profile.display_name
        from public.notification_deliveries as delivery
        left join public.push_subscriptions as subscription
          on subscription.id = delivery.subscription_id
        left join public.profiles as profile
          on profile.id = delivery.user_id
        order by delivery.created_at desc, delivery.id desc
        limit v_limit
      ) as recent_delivery
    ), '[]'::jsonb)
  )
  into v_result
  from public.notification_system_settings as setting
  where setting.singleton = true;

  return v_result;
end;
$$;

