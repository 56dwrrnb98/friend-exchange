-- Preserve and register any auth accounts if this setup is applied to a
-- project that already contains users.
insert into public.approved_signup_emails (
  email,
  added_at,
  registered_user_id,
  registered_at
)
select
  lower(btrim(auth_user.email)),
  auth_user.created_at,
  auth_user.id,
  auth_user.created_at
from auth.users as auth_user
where nullif(btrim(auth_user.email), '') is not null
on conflict (email) do update
set
  registered_user_id = excluded.registered_user_id,
  registered_at = coalesce(
    public.approved_signup_emails.registered_at,
    excluded.registered_at
  );

