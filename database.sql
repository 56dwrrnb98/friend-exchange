create or replace function public.register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_device_label text,
  p_user_agent text
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_subscription_id uuid;
  v_endpoint text := btrim(coalesce(p_endpoint, ''));
  v_p256dh text := btrim(coalesce(p_p256dh, ''));
  v_auth text := btrim(coalesce(p_auth, ''));
  v_device_label text := btrim(coalesce(p_device_label, ''));
  v_user_agent text := nullif(left(btrim(coalesce(p_user_agent, '')), 512), '');
begin
  if v_user_id is null then
    raise exception 'You must be signed in.';
  end if;

  if char_length(v_endpoint) not between 20 and 4096
     or v_endpoint !~ '^https://' then
    raise exception 'The push service returned an invalid endpoint.';
  end if;

  if char_length(v_p256dh) not between 16 and 1024
     or char_length(v_auth) not between 8 and 512 then
    raise exception 'The push service returned invalid encryption keys.';
  end if;

  if char_length(v_device_label) not between 2 and 80 then
    raise exception 'Device labels must be between 2 and 80 characters.';
  end if;

  insert into public.push_subscriptions as existing_subscription (
    user_id,
    endpoint,
    p256dh,
    auth,
    device_label,
    user_agent,
    updated_at,
    last_seen_at,
    disabled_at
  )
  values (
    v_user_id,
    v_endpoint,
    v_p256dh,
    v_auth,
    v_device_label,
    v_user_agent,
    now(),
    now(),
    null
  )
  on conflict (endpoint) do update
  set
    user_id = excluded.user_id,
    p256dh = excluded.p256dh,
    auth = excluded.auth,
    device_label = excluded.device_label,
    user_agent = excluded.user_agent,
    updated_at = now(),
    last_seen_at = now(),
    disabled_at = null
  where existing_subscription.user_id = v_user_id
     or existing_subscription.disabled_at is not null
  returning id into v_subscription_id;

  if v_subscription_id is null then
    raise exception 'That push subscription is already active for another account.';
  end if;

  return v_subscription_id;
end;
$$;

